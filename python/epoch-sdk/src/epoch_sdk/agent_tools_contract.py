"""Closed transport over source-owned EpochAI tools, independent of a supervisor.

Tool parameter schemas are JSON Schema documents generated by their EpochAI
owners. Their keyword/definition names are extensible; this bridge transports
them intact rather than copying their business models into a second SDK.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, JsonValue, model_validator

AgentToolName = Literal["discovery", "inspect_source", "build_study", "audit_run"]
MCP_TOOL_NAMES: dict[AgentToolName, str] = {
    "discovery": "epoch_discover",
    "inspect_source": "epoch_inspect_source",
    "build_study": "epoch_build_study",
    "audit_run": "epoch_audit_run",
}
TOOLS_ASSISTANT_ID = "epoch-tools"
MAX_TOOL_ARGUMENT_BYTES = 128 * 1024


class ToolContract(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True, strict=True)


class AgentToolDefinition(ToolContract):
    name: AgentToolName
    description: str
    parameters: dict[str, JsonValue]
    llm: Literal["none", "specialist"]


class AgentToolsCatalog(ToolContract):
    version: Literal[1, 2] = 1
    assistant_id: Literal["epoch-tools"] = TOOLS_ASSISTANT_ID
    tools: list[AgentToolDefinition]

    @model_validator(mode="after")
    def complete_roster(self) -> AgentToolsCatalog:
        names = [tool.name for tool in self.tools]
        expected = set(MCP_TOOL_NAMES)
        if self.version == 2:
            expected.remove("discovery")
        if len(names) != len(expected) or set(names) != expected:
            raise ValueError("The Epoch tools catalogue must contain each supported tool once")
        return self


class AgentToolHandle(ToolContract):
    workspace_id: str = Field(min_length=1)
    run_id: str = Field(min_length=1)
    tool_call_id: str = Field(min_length=1)
    tool: AgentToolName


class ToolWorkspace(ToolContract):
    workspace_id: str
    studies: dict[str, str] = Field(default_factory=dict)
    executions: dict[str, str] = Field(default_factory=dict)
