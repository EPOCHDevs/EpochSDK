"""Keep outbound TypeScript request serialization consistent with native OpenAPI.

Close outbound serialization only for objects declared closed by the native
selected request graphs. Reject explicit null for their source-owned non-null
defaults before Fern's optional serializer can erase it. Keep generated fields,
enums and genuine nullable types authoritative; never maintain a field roster.
"""

import argparse
import json
import os
import re
from pathlib import Path

MARKER = "// Source-owned outbound closure from canonical native OpenAPI."
INTEGER_MARKER = "// Source-owned bounded integer from canonical native OpenAPI."
HELPER = """"use strict";
// Generated by the source-owned request normalizer; do not edit this artifact.
const {getSchemaUtils} = require("./schemas/builders/schema-utils");
const {getObjectLikeUtils} = require("./schemas/builders/object-like");
const {getObjectUtils} = require("./schemas/builders/object/object");
exports.sourceOwnedClosedRequest = function(schema, nonNullDefaults = [], closeObject = true, closeInput = false) {
    if (typeof schema.parse !== "function" || typeof schema.json !== "function" || typeof schema._getRawProperties !== "function" ||
        typeof schema._getParsedProperties !== "function") {
        throw new Error("Source-owned request closure requires the pinned object serializer ABI");
    }
    const nullErrors = (value, options, parsed) => {
        const rawKeys = schema._getRawProperties();
        const parsedKeys = schema._getParsedProperties();
        if (rawKeys.length !== parsedKeys.length) {
            throw new Error("Source-owned request defaults require paired raw/parsed property keys");
        }
        const keys = nonNullDefaults.map(rawKey => {
            const index = rawKeys.indexOf(rawKey);
            if (index < 0) throw new Error(`Native default property missing from generated serializer: ${rawKey}`);
            return parsed ? parsedKeys[index] : rawKey;
        });
        if (value === null || typeof value !== "object" || Array.isArray(value)) return [];
        return keys.filter(key => Object.prototype.hasOwnProperty.call(value, key) && value[key] === null)
            .map(key => ({path: [...(options?.breadcrumbsPrefix ?? []), key],
                message: `Native default property "${key}" does not accept null`}));
    };
    const closed = {...schema, parse: (value, options) => {
        const errors = nullErrors(value, options, false);
        if (errors.length) return {ok: false, errors};
        if (closeInput && closeObject && value !== null && typeof value === "object" && !Array.isArray(value)) {
            const known = new Set(schema._getRawProperties());
            const extra = Object.keys(value).filter(key => !known.has(key));
            if (extra.length) return {ok: false, errors: extra.map(key => ({
                path: [...(options?.breadcrumbsPrefix ?? []), key],
                message: `Unexpected key "${key}"`,
            }))};
        }
        return schema.parse(value, closeInput ? {...options, skipValidation: false,
            allowUnrecognizedEnumValues: false} : options);
    }, json: (value, options) => {
        const errors = nullErrors(value, options, true);
        if (errors.length) return {ok: false, errors};
        // Derive allowed keys from the generated schema. An already-passthrough
        // serializer may internally override options, so check before delegating.
        if (closeObject && value !== null && typeof value === "object" && !Array.isArray(value)) {
            const known = new Set(schema._getParsedProperties());
            const extra = Object.keys(value).filter(key => !known.has(key));
            if (extra.length) return {ok: false, errors: extra.map(key => ({
                path: [...(options?.breadcrumbsPrefix ?? []), key],
                message: `Unexpected key "${key}"`,
            }))};
        }
        return schema.json(value, {...options,
            ...(closeInput ? {allowUnrecognizedEnumValues: false} : {}),
            ...(closeObject ? {unrecognizedObjectKeys: "fail"} : {}), skipValidation: false});
    }};
    // Rebind composition helpers to this object so optional/lazy/extended
    // shapes cannot retain a closure over the original permissive serializer.
    return Object.assign(closed, getSchemaUtils(closed), getObjectLikeUtils(closed), getObjectUtils(closed));
};
exports.sourceOwnedInteger = function(schema, minimum, maximum) {
    const validate = (value, options, encode) => {
        if (!Number.isSafeInteger(value) || value < minimum || value > maximum) {
            return {ok: false, errors: [{path: options?.breadcrumbsPrefix ?? [],
                message: `Expected an integer in ${minimum}..${maximum}`} ]};
        }
        return encode ? schema.json(value, options) : schema.parse(value, options);
    };
    const exact = {...schema, parse: (value, options) => validate(value, options, false),
        json: (value, options) => validate(value, options, true)};
    return Object.assign(exact, getSchemaUtils(exact));
};
"""


def normalize(name):
    return re.sub(r"[^a-z0-9]", "", name.lower())


def references(value):
    if isinstance(value, dict):
        ref = value.get("$ref")
        if isinstance(ref, str) and ref.startswith("#/components/schemas/"):
            yield ref.rsplit("/", 1)[-1]
        for child in value.values():
            yield from references(child)
    elif isinstance(value, list):
        for child in value:
            yield from references(child)


def allows_null(schema, components, seen=frozenset()):
    """Resolve nullability only for properties that have an explicit default."""
    kind = schema.get("type")
    if schema.get("nullable") is True or kind == "null" or (
        isinstance(kind, list) and "null" in kind
    ):
        return True
    if any(allows_null(arm, components, seen) for key in ("anyOf", "oneOf")
           for arm in schema.get(key, [])):
        return True
    if "allOf" in schema and all(
        allows_null(arm, components, seen) for arm in schema["allOf"]
    ):
        return True
    if "$ref" in schema:
        reference = schema["$ref"]
        name = reference.removeprefix("#/components/schemas/")
        if name == reference or name in seen or name not in components:
            raise ValueError(f"Unresolved native default nullability: {reference}")
        return allows_null(components[name], components, seen | {name})
    return False


def wrapped_body_clients(root: Path, document):
    """Align Fern's reusable-body runtime with its generated public signature.

    The pinned generator can declare {body: Component} but serialize the outer
    request as Component. Derive both the component and method from OpenAPI;
    unwrap only a sole generated body property whose type matches that owner.
    """
    schemas = document["components"]["schemas"]
    operations = {}
    for methods in document.get("paths", {}).values():
        for operation in methods.values():
            if not isinstance(operation, dict) or "operationId" not in operation:
                continue
            schema = operation.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema", {})
            ref = schema.get("$ref", "")
            if not ref.startswith("#/components/schemas/"):
                continue
            name = ref.rsplit("/", 1)[-1]
            if name not in schemas or "body" in schemas[name].get("properties", {}):
                continue
            parts = operation["operationId"].split("_")
            method = parts[0] + "".join(part[:1].upper() + part[1:] for part in parts[1:])
            operations[method] = name
    outputs = []
    for client in sorted((root / "api").rglob("Client.js")):
        declarations = client.with_suffix(".d.ts")
        if not declarations.exists():
            continue
        source, types = client.read_text(), declarations.read_text()
        for method, component in operations.items():
            signature = re.search(r"\b" + re.escape(method) + r"\([^;]*?\brequest:\s*\w+\.(\w+)", types)
            if not signature:
                continue
            wrapper = client.parent / "requests" / (signature[1] + ".d.ts")
            if not wrapper.exists():
                continue
            body = re.search(r"export interface \w+\s*\{\s*body:\s*\w+\.(\w+);\s*\}", wrapper.read_text())
            if not body or normalize(body[1]) != normalize(component):
                continue
            section = re.search(r"(?m)^    __" + re.escape(method) + r"\([^)]*\)\s*\{[\s\S]*?^    \}", source)
            if not section:
                raise ValueError(f"Unrecognized generated wrapped-body method: {method}")
            pattern = r"(body:\s*serializers\." + re.escape(body[1]) + r"\.jsonOrThrow\()request(?=\s*,)"
            repaired, count = re.subn(pattern, r"\1request.body", section[0])
            if count != 1:
                already = re.search(pattern.replace(r"request(?=", r"request\.body(?="), section[0])
                if count != 0 or not already:
                    raise ValueError(f"Unrecognized generated wrapped-body serializer: {method}")
            source = source[:section.start()] + repaired + source[section.end():]
        if source != client.read_text():
            outputs.append((client, source))
    return outputs


def apply(root: Path, spec: Path):
    document = json.loads(spec.read_text())
    schemas = document["components"]["schemas"]
    client_outputs = wrapped_body_clients(root, document)
    pending = [
        name
        for name in schemas
        if name.startswith(("NativeObservation", "DataPreview", "Discovery", "DatasetCatalog", "DatasetSearch", "ScreenAssets", "StudyData", "SubmitPortfolioSnapshot", "DatasetBuild", "Web"))
        and name.endswith("Request")
    ]
    if "ProbeMarketRequest" in schemas:
        pending.append("ProbeMarketRequest")
    if "AssetScreen" in schemas:
        pending.append("AssetScreen")
    reached = {}
    while pending:
        name = pending.pop()
        if name in reached:
            continue
        reached[name] = schemas[name]
        pending.extend(references(schemas[name]))
    identity_reached = set()
    pending = ['StockProfileIdentity'] if 'StockProfileIdentity' in schemas else []
    while pending:
        name = pending.pop()
        if name in identity_reached:
            continue
        if name not in schemas:
            raise ValueError(f"Missing native identity component: {name}")
        identity_reached.add(name)
        reached[name] = schemas[name]
        pending.extend(references(schemas[name]))
    identity_objects = {'#/components/schemas/' + name for name in identity_reached
                        if 'properties' in schemas[name]}
    identity_envelopes = {name: schema for name, schema in schemas.items()
                          if any(field.get('$ref') in identity_objects
                                 for field in schema.get('properties', {}).values())}
    closure_only = identity_envelopes.keys() - reached.keys()
    reached.update(identity_envelopes)
    # Envelope closure also applies to ordinary client parsing. Its unrelated
    # defaults/nullability keep their existing generated behavior.
    # Match Fern's generated inline web objects by their entire wire field set.
    # Their property-derived names are generator details, not native type names.
    inline_web = [(name, arm) for name, schema in reached.items()
                  if name.startswith("Web") for arm in schema.get("oneOf", [])
                  if arm.get("additionalProperties") is False and "properties" in arm]
    for file in sorted((root / "serialization/types").glob("Web*.js")):
        source = file.read_text()
        body = re.search(r"exports\." + re.escape(file.stem)
                         + r"\s*=\s*core\.serialization\.object\(\{\n(.*?)\n\}\)", source, re.S)
        if body is None:
            continue
        fields = set()
        for field, value in re.findall(r"^    (\w+): (.+)$", body[1], re.M):
            alias = re.match(r'core\.serialization\.property\("([^"]+)"', value)
            fields.add(alias[1] if alias else field)
        matches = [arm for name, arm in inline_web
                   if normalize(file.stem).startswith(normalize(name))
                   and fields == set(arm["properties"])]
        if len(matches) > 1:
            raise ValueError(f"Ambiguous native inline web serializer: {file.stem}")
        if matches:
            reached[file.stem] = matches[0]
    non_null_defaults = {
        name: sorted(key for key, field in schema.get("properties", {}).items()
                     if "default" in field and field["default"] is not None
                     and not allows_null(field, schemas))
        for name, schema in reached.items()
    }
    for name in closure_only:
        non_null_defaults[name] = []
    for name in identity_reached:
        schema = reached[name]
        required = set(schema.get('required', []))
        non_null_defaults[name] = sorted(set(non_null_defaults[name]) | {
            key for key, field in schema.get('properties', {}).items()
            if key not in required and not allows_null(field, schemas)
        })
    closed = {
        normalize(name): name
        for name, schema in reached.items()
        if "properties" in schema and schema.get("additionalProperties") is False
    }
    targets = {
        normalize(name): name
        for name, schema in reached.items()
        if ("properties" in schema and schema.get("additionalProperties") is False)
        or non_null_defaults[name]
    }
    if len(targets) != sum(
        ("properties" in schema and schema.get("additionalProperties") is False)
        or bool(non_null_defaults[name]) for name, schema in reached.items()
    ):
        raise ValueError("Ambiguous native component names")
    if not targets:
        for file, output in client_outputs:
            file.write_text(output)
        return {"closed_components": [], "changed_files": len(client_outputs)}
    outputs = []
    found = set()
    # Fern places flattened endpoint request roots under resources/.../requests
    # and reusable DTOs under types. Both belong to the native request graph.
    for file in sorted((root / "serialization").rglob("*.js")):
        key = normalize(file.stem)
        if key not in targets:
            continue
        name = file.stem
        source = file.read_text().split(MARKER, 1)[0].rstrip() + "\n"
        if not re.search(r"exports\." + re.escape(name) + r"\s*=", source):
            raise ValueError(
                f"Native component has no matching generated export: {file}"
            )
        helper = Path(
            os.path.relpath(root / "core/sourceOwnedRequestSchema", file.parent)
        ).as_posix()
        if not helper.startswith("."):
            helper = "./" + helper
        output = (
            source
            + "\n"
            + MARKER
            + "\n"
            + (
                f"exports.{name} = require({json.dumps(helper)}).sourceOwnedClosedRequest("
                f"exports.{name}, {json.dumps(non_null_defaults[targets[key]])}, "
                f"{json.dumps(key in closed)}"
                + (", true" if targets[key] in identity_reached or targets[key] in identity_envelopes else "") + ");\n"
            )
        )
        outputs.append((file, output))
        found.add(key)
    missing = sorted(targets[key] for key in targets.keys() - found)
    if missing:
        raise ValueError(
            f"Native closed request objects lack a mapped generated serializer: {missing}"
        )
    # Fern represents bounded native integer aliases as unconstrained numbers.
    # Keep only aliases whose entire source range is exactly representable in JS;
    # 64-bit value policies remain with their existing lossless serializers.
    integer_aliases = {
        normalize(name): schema for name, schema in reached.items()
        if schema.get('type') == 'integer' and 'enum' not in schema
        and isinstance(schema.get('minimum'), (int, float))
        and isinstance(schema.get('maximum'), (int, float))
        and -9007199254740991 <= schema['minimum'] <= schema['maximum'] <= 9007199254740991
    }
    for file in sorted((root / 'serialization/types').glob('*.js')):
        schema = integer_aliases.get(normalize(file.stem))
        if schema is None:
            continue
        name = file.stem
        source = file.read_text().split(INTEGER_MARKER, 1)[0].rstrip() + '\n'
        if not re.search(r'exports\.' + re.escape(name) + r'\s*=', source):
            raise ValueError(f'Native integer alias has no generated export: {file}')
        helper = Path(os.path.relpath(root / 'core/sourceOwnedRequestSchema', file.parent)).as_posix()
        if not helper.startswith('.'):
            helper = './' + helper
        outputs.append((file, source + '\n' + INTEGER_MARKER + '\n' +
            f'exports.{name} = require({json.dumps(helper)}).sourceOwnedInteger(exports.{name}, '
            f'{schema["minimum"]}, {schema["maximum"]});\n'))
    changed = 0
    for file, output in [*outputs, *client_outputs, (root / "core/sourceOwnedRequestSchema.js", HELPER)]:
        if not file.exists() or file.read_text() != output:
            file.write_text(output)
            changed += 1
    return {"closed_components": sorted(closed.values()), "changed_files": changed,
            "non_null_default_properties": {name: keys for name, keys in sorted(non_null_defaults.items()) if keys}}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--typescript", type=Path, required=True)
    parser.add_argument("--openapi", type=Path, required=True)
    args = parser.parse_args()
    print(json.dumps(apply(args.typescript, args.openapi)))
